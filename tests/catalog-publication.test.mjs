import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {database,asAccount,A,B} from './helpers/writing-cloud.mjs';
test('catalog publication, retry, access, versions and withdrawal preserve exact content',async()=>{
 const db=await database();
 try {
 await db.exec(`create schema storage; create table storage.buckets(id text,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);create table storage.objects(bucket_id text,name text);alter table storage.objects enable row level security;`);
 for(const migration of ['202611110001_content_admin.sql','202611110002_content_admin_operations.sql','202611110003_catalog_publication.sql'])await db.exec(await readFile(new URL('../supabase/migrations/'+migration,import.meta.url),'utf8'));
 await db.query('insert into public.circle_content_admins values($1)',[A]);
 const asset='33333333-3333-4333-8333-333333333333';
 await db.exec(`grant usage on schema storage to authenticated;grant select on storage.objects to authenticated;`);
 await db.query("insert into public.circle_content_assets values($1,'Tree','image/png',9,now())",[asset]);
 await db.query("insert into storage.objects values('circle-content',$1)",[asset]);
 assert.deepEqual(await asAccount(db,B,async tx=>(await tx.query('select * from storage.objects')).rows),[]);
 const rpc=(who,name,value)=>asAccount(db,who,async tx=>(await tx.query(`select public.${name}($1) as result`,[value])).rows[0].result);
 const draft={draftId:'article-test',article:{title:'First',summary:'',blocks:[{id:'one',type:'paragraph',text:'Original'}]}};
 draft.article.cover={assetId:asset,alt:'Original tree',caption:'Original caption'};
 await asAccount(db,A,tx=>tx.query('select public.circle_save_content_draft($1,0,$2)',[draft,crypto.randomUUID()]));
 const command={action:'publish',id:draft.draftId,draftId:draft.draftId,draftRevision:1,draft,expectedRevision:0,operationId:crypto.randomUUID()};
 await assert.rejects(rpc(B,'circle_catalog_change',command),/Admin required/);
 const first=await rpc(A,'circle_catalog_change',command);assert.equal(first.version,1);
 assert.equal((await asAccount(db,B,async tx=>(await tx.query('select * from storage.objects')).rows)).length,1);
 assert.deepEqual(await rpc(A,'circle_catalog_change',command),first);
 await assert.rejects(rpc(A,'circle_catalog_change',{...command,operationId:crypto.randomUUID()}),/Catalog changed/);
 const read=(who,version)=>asAccount(db,who,async tx=>(await tx.query('select public.circle_catalog_read($1,$2) as result',[draft.draftId,version])).rows[0].result);
 assert.equal((await read(B,1)).content.article.title,'First');
 assert.equal((await read(B,1)).content.article.cover.alt,'Original tree');
 assert.equal((await asAccount(db,B,async tx=>(await tx.query('select * from storage.objects')).rows)).length,1);
 await assert.rejects(read(null,1),/Sign in required/);
 const updated=structuredClone(draft);updated.article.title='Second';
 await asAccount(db,A,tx=>tx.query('select public.circle_save_content_draft($1,1,$2)',[updated,crypto.randomUUID()]));
 await rpc(A,'circle_catalog_change',{...command,draft:updated,draftRevision:2,expectedRevision:1,operationId:crypto.randomUUID()});
 assert.equal((await read(B,1)).content.article.title,'First');assert.equal((await read(B,2)).content.article.title,'Second');
 await rpc(A,'circle_catalog_change',{action:'withdraw',id:draft.draftId,expectedRevision:2,operationId:crypto.randomUUID()});
 assert.deepEqual(await asAccount(db,B,async tx=>(await tx.query('select public.circle_catalog_read() as result')).rows[0].result),[]);
 assert.equal((await read(B,1)).content.article.title,'First');
 await rpc(A,'circle_catalog_change',{action:'restore',id:draft.draftId,expectedRevision:3,operationId:crypto.randomUUID()});
 assert.equal((await asAccount(db,B,async tx=>(await tx.query('select public.circle_catalog_read() as result')).rows[0].result)).length,1);
 }finally{await db.close();}
});
